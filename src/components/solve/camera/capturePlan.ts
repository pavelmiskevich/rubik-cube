export type CameraProblem =
  /** Страница открыта не по защищённому соединению — браузер камеру не даст. */
  | "insecure"
  /** Браузер не умеет давать сайтам камеру. */
  | "unsupported"
  /** Человек отказал, или доступ запрещён настройками. */
  | "denied"
  /** Камеры у устройства нет. */
  | "missing"
  /** Камера занята другим приложением. */
  | "busy"
  /** Камера была и пропала: вкладку свернули, устройство отключили. */
  | "ended"
  /** Всё остальное. */
  | "failed";

/** Можно ли вообще просить камеру — до того, как спросить человека. */
export function cameraSupport(environment: {
  isSecureContext: boolean;
  hasGetUserMedia: boolean;
}): CameraProblem | null {
  if (!environment.isSecureContext) return "insecure";
  if (!environment.hasGetUserMedia) return "unsupported";
  return null;
}

const BY_NAME: Readonly<Record<string, CameraProblem>> = {
  NotAllowedError: "denied",
  PermissionDeniedError: "denied",
  SecurityError: "denied",
  NotFoundError: "missing",
  DevicesNotFoundError: "missing",
  OverconstrainedError: "missing",
  NotReadableError: "busy",
  TrackStartError: "busy",
};

/** Что стряслось, по ошибке, которой браузер отказал в камере. */
export function problemOf(error: unknown): CameraProblem {
  const name =
    typeof error === "object" && error !== null && "name" in error
      ? String((error as { name: unknown }).name)
      : "";
  return BY_NAME[name] ?? "failed";
}

