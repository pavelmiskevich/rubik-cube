import { ALGORITHMS, positionFor, repeat } from "./algorithms";
import type { Lesson, LessonStep } from "./types";

const CROSS = ALGORITHMS.lastCross;

/**
 * Перемешивает верхний слой, не переворачивая его рёбер: углы крутятся и
 * меняются местами, рёбра меняются местами. Узор рёбер на верхней грани —
 * точка, уголок или палочка — от этого не меняется, а после алгоритма
 * получается белый крест среди пёстрых углов, как и будет на настоящем кубике.
 */
const CORNERS_MIXED = `${ALGORITHMS.lastFace} U ${ALGORITHMS.lastCorners} U' ${ALGORITHMS.lastEdges}`;

const step = (fields: Omit<LessonStep, "setup" | "goal">): LessonStep => ({
  ...fields,
  setup: positionFor(fields.algorithm, CORNERS_MIXED),
  goal: { kind: "lastLayerCross", face: "U" },
});

/**
 * Урок 5: белый крест на последнем слое.
 *
 * Один алгоритм и три узора. Цвета боковых наклеек здесь не важны — только
 * белое сверху; рёбра по местам расставит последний урок.
 */
export const lastLayerCrossLesson: Lesson = {
  slug: "last-layer-cross",
  title: "Крест на последнем слое",
  summary:
    "Белый крест на верхней грани. Один алгоритм, который повторяют, пока крест не сложится.",
  steps: [
    step({
      id: "line",
      title: "Палочка",
      explanation:
        "Последний слой — верхний, с белым центром. Два нижних слоя уже собраны, и теперь все алгоритмы устроены так, что возвращают их на место. Смотрим только на верхнюю грань и на рёбра: где у них белое смотрит вверх. Если белое вверх у двух противоположных рёбер, с центром получается палочка. Поверните верхний слой так, чтобы палочка лежала поперёк, слева направо, и сделайте F R U R' U' F'. Боковые цвета рёбер пока не важны: креста из белого сверху достаточно.",
      algorithm: CROSS,
    }),
    step({
      id: "corner",
      title: "Уголок",
      explanation:
        "Белое вверх у двух соседних рёбер — вместе с центром получается уголок. Поверните верхний слой так, чтобы уголок смотрел назад и влево: белые рёбра — сзади и слева. После алгоритма уголок превратится в палочку, уже лежащую поперёк, — и второй раз тот же алгоритм даёт крест.",
      algorithm: repeat(CROSS, 2),
    }),
    step({
      id: "dot",
      title: "Точка",
      explanation:
        "Ни у одного ребра белое не смотрит вверх — на верхней грани одна точка, белый центр. Делаем алгоритм как есть, с любой стороны: появится уголок. Дальше знакомо — повернуть верх, чтобы уголок смотрел назад и влево (здесь U2), и ещё дважды тот же алгоритм. Других узоров не бывает: одно или три ребра белым вверх на настоящем кубике не встречаются.",
      algorithm: `${CROSS} U2 ${repeat(CROSS, 2)}`,
    }),
  ],
};
