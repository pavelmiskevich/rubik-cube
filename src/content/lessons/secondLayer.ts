import { ALGORITHMS, positionFor } from "./algorithms";
import type { Lesson, LessonStep } from "./types";

/**
 * В стартовых позициях перемешан верхний слой, два нижних не тронуты. После
 * алгоритма собраны два слоя, а верх так и остаётся пёстрым.
 */
const LAST_LAYER_MIXED = `${ALGORITHMS.lastCross} U ${ALGORITHMS.lastFace} U2 ${ALGORITHMS.lastCorners}`;

const step = (fields: Omit<LessonStep, "setup" | "goal">): LessonStep => ({
  ...fields,
  setup: positionFor(fields.algorithm, LAST_LAYER_MIXED),
  goal: { kind: "twoLayers", face: "D" },
});

