import { ALGORITHMS, positionFor, repeat } from "./algorithms";
import type { Lesson, LessonStep } from "./types";

const FACE = ALGORITHMS.lastFace;

/**
 * Перемешивает верхний слой, ничего в нём не поворачивая: углы и рёбра только
 * меняются местами. Узор белого сверху от этого тот же, а после алгоритма
 * верх белый, но по бокам ещё пестро — как и будет на настоящем кубике.
 */
const PLACES_MIXED = `${ALGORITHMS.lastCorners} U ${ALGORITHMS.lastEdges}`;

const step = (fields: Omit<LessonStep, "setup" | "goal">): LessonStep => ({
  ...fields,
  setup: positionFor(fields.algorithm, PLACES_MIXED),
  goal: { kind: "lastLayerOriented", face: "U" },
});

/**
 * Урок 6: верхняя грань целиком белая.
 *
 * Один алгоритм и правило, как держать кубик перед ним, зависящее от числа
 * углов белым вверх. `method.test.ts` проверяет это правило на всех 27
 * раскладах углов.
 */
export const lastLayerFaceLesson: Lesson = {
  slug: "last-layer-face",
  title: "Белая верхняя грань",
  summary:
    "Белый крест уже есть, теперь углы: поворачиваем их белым вверх, пока верхняя грань не станет белой целиком.",
  steps: [
    step({
      id: "fish",
      title: "Рыбка",
      explanation:
        "Крест сверху белый, осталось повернуть углы белым вверх. Сосчитайте углы, у которых белое уже смотрит вверх. Если такой угол один, белое на верхней грани складывается в рыбку: крест — тело, угол — голова. Поверните верхний слой, чтобы этот угол оказался слева спереди, и сделайте R U R' U R U2 R'. Здесь рыбка готова сразу.",
      algorithm: FACE,
    }),
    step({
      id: "fish-again",
      title: "Рыбка, которой одного раза мало",
      explanation:
        "Снова один угол белым вверх, но другая рыбка. Её не нужно отличать заранее: делаем то же самое, а после алгоритма смотрим ещё раз. Здесь сначала U — поставить белый угол слева спереди, — затем алгоритм, и получается рыбка снова. Опять ставим её угол слева спереди, здесь это U2, и алгоритм. Верх белый.",
      algorithm: `U ${FACE} U2 ${FACE}`,
    }),
    step({
      id: "none-up",
      title: "Ни одного угла белым вверх",
      explanation:
        "Если белым вверх не смотрит ни один угол, найдите угол, у которого белое смотрит влево, и поверните верхний слой, чтобы он оказался слева спереди. Здесь он уже там. После алгоритма появится рыбка — и дальше по первому правилу.",
      algorithm: repeat(FACE, 2),
    }),
    step({
      id: "two-up",
      title: "Два угла белым вверх",
      explanation:
        "Если белым вверх смотрят два угла, поверните верхний слой так, чтобы у левого переднего угла белое смотрело на вас. Здесь для этого нужно U. Дальше алгоритм, и снова по правилам: сколько углов теперь белым вверх, так их и ставим. Этот случай самый длинный — три алгоритма, — но больше трёх не понадобится ни разу.",
      algorithm: `U ${FACE} U ${FACE} U2 ${FACE}`,
    }),
  ],
};
