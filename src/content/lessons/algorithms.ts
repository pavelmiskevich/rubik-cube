import { formatSequence, invertSequence, parseSequence } from "@/lib/cube/moves";

/**
 * Алгоритмы курса в одном месте.
 *
 * Уроки берут их отсюда, и отсюда же их берёт `method.test.ts`, который
 * проверяет не отдельный пример, а правило целиком: если действовать так, как
 * написано в объяснении, любой случай шага доводится до цели. Будь у урока
 * своя копия строки, тест проверял бы одну, а новичок учил бы другую.
 *
 * Все алгоритмы записаны только поворотами граней: движок не понимает
 * поворотов всего куба и срезов, а новичку они и не нужны.
 */
export const ALGORITHMS = {
  /** Угол первого слоя: повторять, пока угол не встанет. */
  corner: "R U R' U'",
  /** Ребро среднего слоя уходит вправо. */
  edgeRight: "U R U' R' U' F' U F",
  /** Ребро среднего слоя уходит влево. */
  edgeLeft: "U' L' U L U F U' F'",
  /** Крест на последнем слое. */
  lastCross: "F R U R' U' F'",
  /** Верхняя грань целиком одного цвета. */
  lastFace: "R U R' U R U2 R'",
  /** Углы последнего слоя по местам. */
  lastCorners: "R' F R' B2 R F' R' B2 R2",
  /** Рёбра последнего слоя по местам. */
  lastEdges: "R U' R U R U R U' R' U' R2",
} as const;

/** `repeat("R U R' U'", 3)` — алгоритм три раза подряд. */
export function repeat(algorithm: string, times: number): string {
  return Array.from({ length: times }, () => algorithm).join(" ");
}

/** Последовательность, отменяющая `algorithm`: обратные ходы в обратном порядке. */
export function undo(algorithm: string): string {
  return formatSequence(invertSequence(parseSequence(algorithm)));
}

/**
 * Стартовая позиция шага: сначала `rest` перемешивает то, до чего шаг ещё не
 * дошёл, затем обратный алгоритм разбирает ровно то, что шаг собирает.
 *
 * Без `rest` алгоритм шага собирал бы куб целиком, и новичок видел бы чудо:
 * четыре хода — и весь кубик готов. С ним после алгоритма собрано ровно то,
 * что обещает шаг, а остальное остаётся перемешанным, как на настоящем кубике.
 * `rest` обязан не трогать то, на что смотрит шаг, — это проверяют тесты:
 * иначе цель шага не была бы достигнута.
 */
export function positionFor(algorithm: string, rest = ""): string {
  return `${rest} ${undo(algorithm)}`.trim();
}
