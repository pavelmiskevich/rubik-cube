/**
 * Перемешивает последний слой, не трогая двух нижних: белая грань уходит,
 * детали верха меняются местами. После алгоритма шага два нижних слоя
 * собраны, а верх пёстрый — как и будет на настоящем кубике, когда до верха
 * ещё не дошли.
 */
const TOP_MIXED = `${ALGORITHMS.lastFace} U ${ALGORITHMS.lastEdges}`;

const step = (fields: Omit<LessonStep, "setup" | "goal">): LessonStep => ({
  ...fields,
  setup: positionFor(fields.algorithm, TOP_MIXED),
  goal: { kind: "twoLayers", face: "D" },
});

